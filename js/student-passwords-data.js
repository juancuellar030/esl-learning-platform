function normalizePasswordToken(value) {
    return String(value || '')
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '')
        .replace(/[^a-zA-Z]/g, '');
}

function getStudentFirstName(fullName) {
    const parts = String(fullName || '').trim().split(/\s+/);
    const candidate = parts[2] || parts[parts.length - 1] || '';
    const normalized = normalizePasswordToken(candidate).toLowerCase();
    return normalized ? normalized.charAt(0).toUpperCase() + normalized.slice(1) : 'Student';
}

function stableStudentNumber(name, group) {
    const raw = `${group}:${name}`;
    let hash = 0;
    for (let i = 0; i < raw.length; i++) {
        hash = (hash * 31 + raw.charCodeAt(i)) % 10000;
    }
    return String((hash % 90) + 10).padStart(2, '0');
}

// Printed cards stay valid when a roster string is corrected.
// Gutierrez is still Samuel; adding DAVID would otherwise change 63 to 95.
// Reyes is still Manuela; GUTIÉRREZ would otherwise change 13 to 73.
const FROZEN_PASSWORD_NUMBERS = {
    "GUTIERREZ HUELGO SAMUEL DAVID": "63",
    "GUTIÉRREZ REYES MANUELA": "13",
};

function specialForStudent(name, group) {
    const slot = Object.prototype.hasOwnProperty.call(PASSWORD_SLOTS, name)
        ? PASSWORD_SLOTS[name]
        : Number(stableStudentNumber(name, group));
    return STUDENT_PASSWORD_SPECIALS[slot % STUDENT_PASSWORD_SPECIALS.length];
}

function buildStudentPasswords(groups) {
    const passwords = {};
    Object.keys(groups || {}).forEach(group => {
        (groups[group] || []).forEach(name => {
            const firstName = getStudentFirstName(name);
            const number = Object.prototype.hasOwnProperty.call(FROZEN_PASSWORD_NUMBERS, name)
                ? FROZEN_PASSWORD_NUMBERS[name]
                : stableStudentNumber(name, group);
            passwords[name] = `${firstName}${specialForStudent(name, group)}${number}`;
        });
    });
    return passwords;
}

